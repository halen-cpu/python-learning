# ============================================================
# 方法 1：help() —— 把"东西"塞进去，它吐出官方说明书
# ============================================================
print("=" * 56)
print("方法 1：help(东西) —— 官方说明书")
print("=" * 56)

# 完整用法（输出很长，想看时把下面这行的 # 去掉再跑）
# help(len)

# 日常更实用：只要第一句话，一眼看完
print("len() 是干嘛的：")
print("   ", len.__doc__.strip().split("\n")[0])

print()
print("字符串的 .split() 是干嘛的：")
print("   ", str.split.__doc__.strip().split("\n")[0])

print()
print("列表的 .append() 是干嘛的：")
print("   ", list.append.__doc__.strip().split("\n")[0])

print()
print(">>> 注意最后那句 print 的写法：")
print("    .__doc__ 就是【这个函数的说明书原文】，")
print("    用 .strip().split(chr(10))[0] 取第一行，省得刷屏。")


# ============================================================
# 方法 2：dir() —— 问"这东西能干什么"
# ============================================================
print()
print("=" * 56)
print("方法 2：dir(东西) —— 列出它身上所有能用的方法")
print("=" * 56)

s = "hello"
# 带下划线开头的 _xxx_ 是 Python 内部的，新手先跳过
usable = [m for m in dir(s) if not m.startswith("_")]

print("一个字符串能干这些事（共", len(usable), "个）：")
for i in range(0, len(usable), 6):
    print("   ", "  ".join(usable[i:i + 6]))

print()
print(">>> 看不懂哪个名字，就 help(str.那个名字)")
print("    例：help(str.upper)   —— 会告诉你它把字母全变大写")


# ============================================================
# 方法 3：交互模式 —— 不懂就直接敲一行试
# ============================================================
